// tsInvariantIDL returns a multi-namespace IDL used by the invariants tests.
// Declaration order is deliberately not sorted (Zebra before Apple, zoo before
// farm) so any map-order leak into emitted bytes is detectable.
func tsInvariantIDL() *parser.IDL {
	return &parser.IDL{
		RootNamespace: "zoo",
		Structs: []*parser.Struct{
			{
				Name:      "Zebra",
				Namespace: "zoo",
				Fields: []*parser.Field{
					{Name: "name", Type: &parser.Type{BuiltIn: "string"}},
					{Name: "weight", Type: &parser.Type{BuiltIn: "float"}},
					{Name: "mood", Type: &parser.Type{UserDefined: "Mood"}},
				},
			},
			{
				Name:      "Apple",
				Namespace: "zoo",
				Fields:    []*parser.Field{{Name: "value", Type: &parser.Type{BuiltIn: "int"}}},
			},
			{
				Name:      "Barn",
				Namespace: "farm",
				Fields:    []*parser.Field{{Name: "label", Type: &parser.Type{BuiltIn: "string"}}},
			},
		},
		Enums: []*parser.Enum{
			{
				Name:      "Mood",
				Namespace: "zoo",
				Values:    []*parser.EnumValue{{Name: "HAPPY"}, {Name: "SAD"}},
			},
			{
				Name:      "Season",
				Namespace: "farm",
				Values:    []*parser.EnumValue{{Name: "SUMMER"}, {Name: "WINTER"}},
			},
		},
		Interfaces: []*parser.Interface{
			{
				Name:      "ZSvc",
				Namespace: "zoo",
				Methods: []*parser.Method{
					{
						Name:       "getZebra",
						Parameters: []*parser.Parameter{{Name: "id", Type: &parser.Type{BuiltIn: "string"}}},
						ReturnType: &parser.Type{UserDefined: "Zebra"},
					},
				},
			},
			{
				Name:      "FSvc",
				Namespace: "farm",
				Methods: []*parser.Method{
					{Name: "getBarn", ReturnType: &parser.Type{UserDefined: "Barn"}},
				},
			},
		},
		Errors: []*parser.ErrorDef{
			{Name: "ZooError", Namespace: "zoo", Code: 1001, Message: "zoo failure"},
		},
	}
}

// collectTsFiles walks root and returns path -> bytes for every regular file.
func collectTsFiles(t *testing.T, root string) map[string][]byte {
	t.Helper()
	files := map[string][]byte{}
	err := filepath.Walk(root, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.IsDir() {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		files[rel] = data
		return nil
	})
	if err != nil {
		t.Fatalf("walk %s: %v", root, err)
	}
	return files
}

// C1: generation is byte-deterministic. Two fresh runs of the same IDL with
// the same flags must emit exactly the same files and bytes.
func TestTsGenerationIsByteDeterministic(t *testing.T) {
	settings := map[string]string{
		"ts-module":           "cjs",
		"generate-test-files": "true",
		"ts-gen-package-json": "true",
		"ts-gen-tsconfig":     "true",
	}
	// Use the same leaf directory name under two different parents: generated
	// package.json derives its package name from the output directory name.
	dirA := filepath.Join(t.TempDir(), "out")
	dirB := filepath.Join(t.TempDir(), "out")
	if err := os.MkdirAll(dirA, 0755); err != nil {
		t.Fatalf("mkdir %s: %v", dirA, err)
	}
	if err := os.MkdirAll(dirB, 0755); err != nil {
		t.Fatalf("mkdir %s: %v", dirB, err)
	}
	tsRunGenWithFlags(t, tsInvariantIDL(), dirA, settings)
	tsRunGenWithFlags(t, tsInvariantIDL(), dirB, settings)

	filesA := collectTsFiles(t, dirA)
	filesB := collectTsFiles(t, dirB)

	if len(filesA) == 0 {
		t.Fatal("expected generated files")
	}
	for rel := range filesA {
		if _, ok := filesB[rel]; !ok {
			t.Errorf("second generation missing %s", rel)
		}
	}
	for rel := range filesB {
		if _, ok := filesA[rel]; !ok {
			t.Errorf("second generation emitted unexpected %s", rel)
		}
	}
	for rel, a := range filesA {
		b, ok := filesB[rel]
		if !ok {
			continue
		}
		if !bytes.Equal(a, b) {
			t.Errorf("generated bytes differ for %s\nfirst:\n%s\nsecond:\n%s", rel, a, b)
		}
	}
}

// C1/D12: when the IDL has no root namespace, the fallback entry point is the
// first namespace in sorted order (map iteration order must not leak).
func TestTsNamespaceFallbackIsSorted(t *testing.T) {
	idl := tsInvariantIDL()
	idl.RootNamespace = ""
	dir := t.TempDir()
	tsRunGenWithFlags(t, idl, dir, map[string]string{"ts-module": "cjs"})

	if _, err := os.Stat(filepath.Join(dir, "farm", "idl.json")); err != nil {
		t.Errorf("expected idl.json in the first sorted namespace (farm): %v", err)
	}
}

// R16/R18/D5: the generated adapter must cap request bodies at 1 MiB and
// batches at 100 entries using the documented fixed messages.
func TestGeneratedTsTestServerEnforcesRequestLimits(t *testing.T) {
	idl := parseTestIDL(t, "namespace test\ninterface Svc { Ping() string }\n")
	code := generateTestServerTs(idl, nil, nil, nil, "", nil, "test", "")

	for _, want := range []string{
		"const MAX_BODY_SIZE = 1024 * 1024;",
		"const MAX_BATCH_SIZE = 100;",
		"Request body too large",
		"Batch exceeds maximum size",
		"code: -32600",
	} {
		if !strings.Contains(code, want) {
			t.Errorf("generated test server missing %q", want)
		}
	}

	// The batch cap check must run before entries are dispatched.
	capCheck := strings.Index(code, "data.length > MAX_BATCH_SIZE")
	dispatch := strings.Index(code, "Promise.all(data.map")
	if capCheck < 0 || dispatch < 0 || capCheck > dispatch {
		t.Errorf("batch cap (%d) must precede dispatch (%d)", capCheck, dispatch)
	}

	// Oversized bodies must not be buffered after the cap is reached.
	if !strings.Contains(code, "if (oversized)") {
		t.Error("generated adapter must stop buffering once the body cap is exceeded")
	}
}

